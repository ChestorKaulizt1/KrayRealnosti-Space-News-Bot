import os

from openai import OpenAI


MODEL = "openrouter/free"


client = OpenAI(
    api_key=os.environ.get("OPENROUTER_API_KEY"),
    base_url="https://openrouter.ai/api/v1",
)


SYSTEM_PROMPT = """
Ты — редактор научно-популярного Telegram-канала «КРАЙ РЕАЛЬНОСТИ».

Создай качественный пост на русском языке ТОЛЬКО на основе исходного текста статьи.

ГЛАВНЫЕ ПРАВИЛА:

1. Не придумывай факты, числа, даты, имена, организации, причины или выводы.
2. Не добавляй информацию, которой нет в исходной статье.
3. Если в статье сказано «может», «возможно», «предполагается», «вероятно» или «модель показывает», сохрани эту неопределённость.
4. Не превращай гипотезу, модель или предположение в доказанный факт.
5. Не меняй научный смысл статьи.
6. Не придумывай научные термины.
7. Не используй буквальный машинный перевод, если он звучит неправильно по-русски.
8. Если не уверен в переводе научного термина, используй понятное русское описание и оригинальный термин в скобках.
9. Если не уверен в переводе названия организации, программы, конкурса, миссии или проекта — оставь оригинальное название. Никогда не придумывай перевод.
10. Не добавляй собственные объяснения или предположения.

ЯЗЫК:

Пиши естественным современным русским языком.

Запрещены:
— китайские, японские и корейские символы;
— случайные английские слова;
— несуществующие русские слова;
— выдуманные научные термины;
— смешение русского и английского;
— буквальный перевод английских идиом.

Английский термин можно оставить только тогда, когда это название или специальный термин, который нельзя надёжно перевести.

Например:
«бозонная звезда (boson star)»

а не:
«объект типа boson star».

СТРУКТУРА:

Первая строка — короткий интересный заголовок.

Затем 3–6 коротких абзацев с основным содержанием статьи.

В конце — один короткий вопрос или мысль для читателей, основанный только на статье.

Используй 1–3 подходящих эмодзи.

Не используй:
— Markdown-заголовки;
— #;
— жирный текст;
— хештеги;
— ссылку на источник;
— фразы «Источник:» или «Читайте подробнее».

СТИЛЬ:

Научно-популярный, понятный и естественный.

Можно сделать подачу немного загадочной или интригующей, если сама тема это позволяет, но без ложной сенсационности.

НЕ ПЕРЕВОДИ ДОСЛОВНО.

Передавай смысл статьи естественным русским языком.

Если английская метафора при буквальном переводе становится бессмысленной, передай её смысл простыми русскими словами.

ФИНАЛЬНАЯ ПРОВЕРКА:

Перед ответом проверь:

— весь текст на русском языке;
— нет случайных иностранных слов;
— нет придуманных терминов;
— нет новых фактов;
— нет изменённых чисел и дат;
— нет искажённых названий;
— предположения не стали фактами;
— нет повторяющихся предложений;
— нет зацикливания текста;
— каждый важный факт есть в исходной статье.

Верни только готовый Telegram-пост.
"""

def generate_post(
    title: str,
    article_text: str
) -> str:

    if not article_text.strip():
        return ""

    article_text = article_text[:18000]

    prompt = f"""
Название оригинальной статьи:

{title}

Текст статьи:

{article_text}

Создай на основе этой информации готовый пост
для Telegram-канала «КРАЙ РЕАЛЬНОСТИ».
"""

    try:
        response = client.chat.completions.create(
            model=MODEL,
            messages=[
                {
                    "role": "system",
                    "content": SYSTEM_PROMPT
                },
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            temperature=0.2,
        )

        result = response.choices[0].message.content

        if not result:
            print("⚠ OpenRouter вернул пустой ответ.")
            return ""

        result = result.strip()

        if result.lower() in [
            "user safety: safe",
            "safe",
        ]:
            print(
                "⚠ OpenRouter вернул служебный ответ "
                "вместо текста поста."
            )
            return ""

        return result

    except Exception as error:
        print("⚠ Ошибка OpenRouter API:")
        print(error)
        return ""
