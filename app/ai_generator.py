import os
import re

from openai import OpenAI


MODEL = "openrouter/free"


client = OpenAI(
    api_key=os.environ.get("OPENROUTER_API_KEY"),
    base_url="https://openrouter.ai/api/v1",
)


SYSTEM_PROMPT = """
Ты — редактор научно-популярного Telegram-канала «КРАЙ РЕАЛЬНОСТИ».

Создай качественный пост на русском языке ТОЛЬКО на основе исходного текста статьи.

ГЛАВНЫЕ ПРАВИЛА:

1. Не придумывай факты, числа, даты, имена, организации, причины или выводы.
2. Не добавляй информацию, которой нет в исходной статье.
3. Если в статье сказано «может», «возможно», «предполагается», «вероятно» или «модель показывает», сохрани эту неопределённость.
4. Не превращай гипотезу, модель или предположение в доказанный факт.
5. Не меняй научный смысл статьи.
6. Не придумывай научные термины.
7. Не используй буквальный машинный перевод.
8. Если научный термин нельзя надёжно перевести, используй понятное русское описание и оригинальный термин в скобках.
9. Если название организации, программы, конкурса, миссии или проекта нельзя надёжно перевести — оставь оригинальное название.
10. Не добавляй собственные объяснения или предположения.

ЯЗЫК:

Пиши естественным современным русским языком.

Запрещены:
— китайские, японские и корейские символы;
— случайные английские слова;
— несуществующие русские слова;
— выдуманные научные термины;
— смешение русского и английского;
— буквальный перевод английских идиом.

Английский язык разрешён только для:
— официальных названий;
— названий организаций;
— названий программ;
— названий миссий;
— специальных научных терминов, которые лучше оставить в оригинале.

Не оставляй обычные английские слова внутри русского предложения.

Например:

ПЛОХО:
«финальный ревью проекта»

ХОРОШО:
«финальная проверка проекта»

ПЛОХО:
«June 21–24, 2027»

ХОРОШО:
«21–24 июня 2027 года»

ПЛОХО:
«net-заряд»

ХОРОШО:
«электрический заряд»

ПЛОХО:
«NASA Program»

ХОРОШО:
«программа NASA»

СТРУКТУРА:

Первая строка — короткий интересный заголовок.

Затем 3–6 коротких абзацев с основным содержанием статьи.

В конце — один короткий вопрос или мысль для читателей, основанный только на статье.

Используй 1–3 подходящих эмодзи.

Не используй:
— Markdown-заголовки;
— #;
— жирный текст;
— хештеги;
— ссылку на источник;
— фразы «Источник:» или «Читайте подробнее».

СТИЛЬ:

Научно-популярный, понятный и естественный.

Можно сделать подачу немного загадочной или интригующей, если сама тема это позволяет, но без ложной сенсационности.

НЕ ПЕРЕВОДИ ДОСЛОВНО.

Передавай смысл статьи естественным русским языком.

Если английская метафора при буквальном переводе становится бессмысленной, передай её смысл простыми русскими словами.

ФИНАЛЬНАЯ ПРОВЕРКА:

Перед ответом проверь:

— весь текст написан нормальным русским языком;
— нет случайных иностранных слов;
— нет придуманных терминов;
— нет новых фактов;
— нет изменённых чисел и дат;
— нет искажённых названий;
— предположения не стали фактами;
— нет повторяющихся предложений;
— нет зацикливания текста;
— каждый важный факт есть в исходной статье.

Верни только готовый Telegram-пост.
"""


BAD_PATTERNS = [
    r"\bnet[- ]",
    r"\bJune\b",
    r"\bJuly\b",
    r"\bAugust\b",
    r"\bSeptember\b",
    r"\bOctober\b",
    r"\bNovember\b",
    r"\bDecember\b",
    r"\bJanuary\b",
    r"\bFebruary\b",
    r"\bMarch\b",
    r"\bApril\b",
    r"\bMay\b",
    r"\bProgram\b",
    r"\bChallenge\b",
    r"\bReview\b",
    r"\bfinal review\b",
    r"\bMoon Base\b",
    r"\bCoverage\b",
    r"\bStatement\b",
]


def contains_bad_patterns(text: str) -> bool:
    """
    Проверяет пост на очевидные ошибки машинного перевода.
    """

    for pattern in BAD_PATTERNS:
        if re.search(pattern, text, re.IGNORECASE):
            return True

    # Китайские символы
    if re.search(r"[\u4e00-\u9fff]", text):
        return True

    # Японская хирагана/катакана
    if re.search(r"[\u3040-\u30ff]", text):
        return True

    # Корейские символы
    if re.search(r"[\uac00-\ud7af]", text):
        return True

    return False


def fix_generated_post(
    post: str,
    title: str,
    article_text: str,
) -> str:

    correction_prompt = f"""
Ниже находится пост, который был автоматически создан на основе статьи.

В нём могут быть ошибки перевода или случайные английские слова.

ТВОЯ ЗАДАЧА:

Исправь ТОЛЬКО языковые и переводческие ошибки.

Не добавляй новые факты.

Не удаляй важные факты.

Не меняй числа.

Не меняй даты.

Не меняй научный смысл.

Не превращай предположение в факт.

Все обычные английские слова переведи на естественный русский язык.

Официальные названия организаций, программ, миссий и научных терминов можно оставить на английском, если перевод ненадёжен.

Оригинальная статья:

{article_text[:18000]}

Название статьи:

{title}

Пост для исправления:

{post}

Верни ТОЛЬКО полностью исправленный готовый Telegram-пост.
"""

    try:
        response = client.chat.completions.create(
            model=MODEL,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "Ты профессиональный русскоязычный "
                        "редактор научно-популярных текстов."
                    ),
                },
                {
                    "role": "user",
                    "content": correction_prompt,
                },
            ],
            temperature=0.2,
        )

        result = response.choices[0].message.content

        if not result:
            return post

        result = result.strip()

        if result.lower() in [
            "user safety: safe",
            "safe",
        ]:
            return post

        return result

    except Exception as error:
        print("⚠ Ошибка исправления поста:")
        print(error)

        return post


def generate_post(
    title: str,
    article_text: str,
) -> str:

    if not article_text.strip():
        return ""

    article_text = article_text[:18000]

    prompt = f"""
Название оригинальной статьи:

{title}

Текст статьи:

{article_text}

Создай на основе этой информации готовый пост
для Telegram-канала «КРАЙ РЕАЛЬНОСТИ».
"""

    try:
        response = client.chat.completions.create(
            model=MODEL,
            messages=[
                {
                    "role": "system",
                    "content": SYSTEM_PROMPT,
                },
                {
                    "role": "user",
                    "content": prompt,
                },
            ],
            temperature=0.2,
        )

        result = response.choices[0].message.content

        if not result:
            print("⚠ OpenRouter вернул пустой ответ.")
            return ""

        result = result.strip()

        if result.lower() in [
            "user safety: safe",
            "safe",
        ]:
            print(
                "⚠ OpenRouter вернул служебный ответ "
                "вместо текста поста."
            )
            return ""

        # Проверяем результат.
        if contains_bad_patterns(result):
            print()
            print(
                "⚠ Обнаружены возможные ошибки перевода."
            )
            print(
                "↻ Выполняем однократное исправление..."
            )

            fixed_result = fix_generated_post(
                post=result,
                title=title,
                article_text=article_text,
            )

            if fixed_result:
                result = fixed_result

        return result

    except Exception as error:
        print("⚠ Ошибка OpenRouter API:")
        print(error)
        return ""
