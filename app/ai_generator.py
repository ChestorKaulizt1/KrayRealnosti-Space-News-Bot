# Явные признаки плохого машинного перевода.
BAD_PATTERNS = [
    r"\bnet[- ]",
    r"\btoy model\b",
    r"\bJune\b",
    r"\bJuly\b",
    r"\bAugust\b",
    r"\bSeptember\b",
    r"\bOctober\b",
    r"\bNovember\b",
    r"\bDecember\b",
    r"\bJanuary\b",
    r"\bFebruary\b",
    r"\bMarch\b",
    r"\bApril\b",
    r"\bMay\b",
    r"\bProgram\b",
    r"\bChallenge\b",
    r"\bReview\b",
    r"\bStatement\b",
    r"\bCoverage\b",
    r"\bMoon Base\b",
    r"\bfinal review\b",
]


# Фразы, которые часто появляются после плохого машинного перевода.
SUSPICIOUS_PHRASES = [
    "может выстрелить самой",
    "выстрелить самой из",
    "поглощают материи",
    "склеиваться в облако",
    "склеивается в облако",
    "живя как звезда",
    "стала лысыми",
    "ставшей лысыми",
    "ожидают носить",
    "делает черную дыру сдвинуться",
    "делает чёрную дыру сдвинуться",
    "разрушительная симметрия",
    "финальный ревью",
    "финальное ревью",
    "физика традиционно считает",
]


def contains_bad_patterns(text: str) -> bool:
    """
    Проверяет текст на явные признаки плохого перевода.
    """

    for pattern in BAD_PATTERNS:
        if re.search(
            pattern,
            text,
            re.IGNORECASE,
        ):
            return True

    for phrase in SUSPICIOUS_PHRASES:
        if phrase.lower() in text.lower():
            return True

    # Китайские символы.
    if re.search(
        r"[\u4e00-\u9fff]",
        text,
    ):
        return True

    # Японская хирагана/катакана.
    if re.search(
        r"[\u3040-\u30ff]",
        text,
    ):
        return True

    # Корейские символы.
    if re.search(
        r"[\uac00-\ud7af]",
        text,
    ):
        return True

    return False


def fix_generated_post(
    post: str,
    title: str,
    article_text: str,
) -> str:
    """
    Однократная редактура уже созданного поста.
    """

    correction_prompt = f"""
Ниже находится автоматически созданный Telegram-пост.

Он содержит признаки плохого машинного перевода.

Твоя задача — полностью отредактировать этот пост.

ГЛАВНОЕ:

Исправляй язык и перевод.

НЕ добавляй новые факты.

НЕ добавляй новые числа.

НЕ добавляй новые даты.

НЕ добавляй новые имена.

НЕ добавляй новые организации.

НЕ меняй научный смысл.

НЕ превращай гипотезу в факт.

НЕ придумывай официальный перевод названий организаций.

Если официальное название неизвестно,
оставь его на английском языке.

УБЕРИ:

— случайные английские слова;
— буквальный перевод;
— неестественные русские конструкции;
— выдуманные научные термины;
— китайские/японские/корейские символы;
— повторения;
— бессмысленные предложения;
— машинные конструкции.

Пиши естественным русским языком.

Например:

«toy model»
→ «упрощённая модель»

«net-заряд»
→ «электрический заряд»

«June 21–24, 2027»
→ «21–24 июня 2027 года»

«NASA Program»
→ «программа NASA»

Но официальные названия организаций
не переводи самостоятельно.

ВАЖНО:

Если предложение нельзя надёжно перевести,
переформулируй его простыми русскими словами,
сохранив исходный смысл.

Исходная статья:

{article_text[:18000]}

Название статьи:

{title}

Пост:

{post}

Верни только окончательную версию поста.
"""


    try:
        response = client.chat.completions.create(
            model=MODEL,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "Ты опытный русскоязычный редактор "
                        "научно-популярных текстов."
                    ),
                },
                {
                    "role": "user",
                    "content": correction_prompt,
                },
            ],
            temperature=0.2,
        )

        result = response.choices[0].message.content

        if not result:
            return post

        result = result.strip()

        if result.lower() in [
            "user safety: safe",
            "safe",
        ]:
            return post

        return result

    except Exception as error:
        print(
            "⚠ Ошибка исправления поста:"
        )
        print(error)

        return post


def generate_post(
    title: str,
    article_text: str,
) -> str:

    if not article_text.strip():
        return ""

    article_text = article_text[:18000]

    prompt = f"""
Название оригинальной статьи:

{title}

Текст статьи:

{article_text}

Создай на основе этой информации
готовый пост для Telegram-канала
«КРАЙ РЕАЛЬНОСТИ».
"""

    try:
        response = client.chat.completions.create(
            model=MODEL,
            messages=[
                {
                    "role": "system",
                    "content": SYSTEM_PROMPT,
                },
                {
                    "role": "user",
                    "content": prompt,
                },
            ],
            temperature=0.2,
        )

        result = response.choices[0].message.content

        if not result:
            print(
                "⚠ OpenRouter вернул пустой ответ."
            )
            return ""

        result = result.strip()

        if result.lower() in [
            "user safety: safe",
            "safe",
        ]:
            print(
                "⚠ OpenRouter вернул служебный ответ "
                "вместо текста поста."
            )
            return ""

        # Автоматическая проверка.
        if contains_bad_patterns(result):

            print()
            print(
                "⚠ Обнаружены возможные ошибки "
                "перевода."
            )
            print(
                "↻ Выполняем однократную редактуру..."
            )

            fixed_result = fix_generated_post(
                post=result,
                title=title,
                article_text=article_text,
            )

            if fixed_result:
                result = fixed_result

        return result

    except Exception as error:
        print(
            "⚠ Ошибка OpenRouter API:"
        )
        print(error)

        return ""
